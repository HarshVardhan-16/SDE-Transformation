class variables{
    public static void main (String args[])
    {
        System.out.print("Data Type Demonstration");
        int a=10;
        float b=20.5f;
        double c=30.5;
        long f =  372837;
        char e = 'a';
        byte test = 2;
        boolean g = true;

        System.out.println("Integer value: " + a);
        System.out.println("Float value: " + b);
        System.out.println("Double value: " + c);
        System.out.println("Long value: " + f);
        System.out.println("char value: " + e);
        System.out.println("byte value: " + test);
        System.out.println("boolean value: " + g);
    }
}